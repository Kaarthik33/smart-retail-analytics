"""Write reports/insights.md: the manager's five questions answered with the latest numbers."""

from __future__ import annotations

import pandas as pd

from . import config


def _t(name: str) -> pd.DataFrame:
    return pd.read_csv(config.TABLES_DIR / f"{name}.csv")


def _md(df: pd.DataFrame) -> str:
    head = "| " + " | ".join(df.columns) + " |\n|" + "|".join(" --- " for _ in df.columns) + "|\n"
    body = "\n".join("| " + " | ".join(str(v) for v in row) + " |" for row in df.itertuples(index=False))
    return head + body + "\n"


def run() -> None:
    top, cat = _t("top_products_by_revenue"), _t("category_performance")
    wd, mon = _t("sales_by_weekday"), _t("monthly_sales_trend")
    rules, fm = _t("association_rules"), _t("forecast_metrics")
    inv, promo = _t("inventory_plan"), _t("promotion_uplift")
    by_disc = _t("promotion_uplift_by_discount")

    n80 = int((top.cumulative_share_pct < 80).sum() + 1)
    best_day, worst_day = wd.loc[wd.avg_daily_revenue.idxmax()], wd.loc[wd.avg_daily_revenue.idxmin()]
    by_month = mon.groupby("month").revenue.mean()
    month_name = pd.to_datetime(by_month.idxmax(), format="%m").strftime("%B")
    pairs = rules.drop_duplicates("baskets_together").head(8)
    status = inv.status.value_counts()

    lines = [
        "# Smart Retail Analytics - insights report",
        "",
        "_Generated by `python -m retail_analytics.pipeline`. Data: simulated FreshMart sales, "
        f"{mon.year_month.min()} to {mon.year_month.max()}._",
        "",
        "## 1. Which products generate the most revenue?",
        "",
        f"- Total revenue: **€{top.revenue.sum():,.0f}** with a gross margin of "
        f"**{100 * top.gross_profit.sum() / top.revenue.sum():.1f}%**.",
        f"- **{top.product_name[0]}** is the #1 product (€{top.revenue[0]:,.0f}, "
        f"{top.revenue_share_pct[0]}% of revenue).",
        f"- **{n80} of {len(top)} products** generate 80% of revenue.",
        f"- Largest category: **{cat.category[0]}** ({cat.revenue_share_pct[0]}% of revenue). "
        f"Highest margin: **{cat.loc[cat.margin_pct.idxmax(), 'category']}** "
        f"({cat.margin_pct.max()}%).",
        "",
        _md(top.head(10)[["revenue_rank", "product_name", "category", "units_sold", "revenue",
                          "margin_pct", "cumulative_share_pct"]]),
        "## 2. Which products are frequently purchased together?",
        "",
        _md(pairs.assign(support_pct=(pairs.support * 100).round(2),
                         confidence_pct=(pairs.confidence * 100).round(1))
            [["antecedent", "consequent", "support_pct", "confidence_pct", "lift"]]),
        "## 3. Which days and seasons have the highest sales?",
        "",
        f"- **{best_day.weekday}** is the strongest day ({best_day.index_vs_avg_day - 100:+.0f}% vs. "
        f"an average day); **{worst_day.weekday}** is the weakest "
        f"({worst_day.index_vs_avg_day - 100:+.0f}%).",
        f"- **{month_name}** is the strongest month on average "
        f"(€{by_month.max():,.0f}); year-over-year growth averaged "
        f"**{mon.yoy_growth_pct.mean():+.1f}%**.",
        "",
        "## 4. How much inventory should be maintained?",
        "",
        f"- Forecast accuracy on 8 unseen weeks: **{fm.wape_weekly_pct[0]}% weekly WAPE** vs. "
        f"{fm.wape_weekly_pct[1]}% for \"same weekday last week\" and {fm.wape_weekly_pct[2]}% "
        "for a 4-week average.",
        f"- Of {len(inv)} store-product combinations: **{status.get('Reorder now', 0)} need "
        f"reordering now**, {status.get('Overstocked', 0)} are overstocked, "
        f"{status.get('Healthy', 0)} are healthy.",
        f"- Recommended order value: **€{inv.order_value_eur.sum():,.0f}**; capital tied up in "
        f"excess stock: **€{inv.excess_stock_value_eur.sum():,.0f}** (both at cost).",
        "",
        "## 5. What happens to sales during promotions?",
        "",
        f"- Across {len(promo)} promotions, units sold rose by **{promo.unit_uplift_pct.mean():+.0f}%** "
        "on average.",
        f"- Only **{100 * (promo.incremental_profit > 0).mean():.0f}%** of promotions increased "
        f"gross profit; in total they changed profit by "
        f"**{'-' if promo.incremental_profit.sum() < 0 else '+'}"
        f"€{abs(promo.incremental_profit.sum()):,.0f}** "
        f"while adding €{promo.incremental_revenue.sum():,.0f} of revenue.",
        "",
        _md(by_disc),
    ]
    (config.REPORTS_DIR / "insights.md").write_text("\n".join(lines))
    print("  wrote reports/insights.md")


if __name__ == "__main__":
    run()
